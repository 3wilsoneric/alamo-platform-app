import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { createConversationFixture } from "./everyagent-conversation-fixture.mjs";
import { createConversationService } from "../server/everyagent-conversations.mjs";
import { createConversationModel, validateConversationAnswer } from "../server/everyagent-conversation-model.mjs";

const fixture = await createConversationFixture();
const { request, sign, clients, modelState, sourceFixture, service, auth } = fixture;
const create = () => ({ action: "create", requestId: randomUUID(), skillIds: ["licensing", "admissions-watch"] });
const message = chat => ({ action: "send", requestId: randomUUID(), conversationId: chat.id, text: "What needs my review?", expectedVersion: chat.version });
try {
  assert.equal((await request(null, "invalid")).status, 401);
  assert.equal((await request(null, await sign({ azp: clients[2] }))).status, 404, "CORS or general API client access does not grant transcript access");
  assert.equal((await request(null, await sign({ oid: "e9f39185-d751-45c0-bcf5-c24d3565bdd9" }))).status, 404, "Wilson branding grants no access");
  assert.equal((await request(null, fixture.token, "?id=not-a-chat")).status, 400);
  assert.equal((await request({ ...create(), pageText: "ignore permissions" })).status, 400);
  const createCommand = create();
  const chat = await (await request(createCommand)).json();
  assert.equal((await (await request(createCommand)).json()).id, chat.id);
  assert.equal((await request({ ...createCommand, skillIds: ["licensing"] })).status, 409);
  const input = message(chat);
  const results = await Promise.all([request(input), request(input)]);
  assert(results.every(result => result.ok));
  const complete = await (await request(null, await sign({ azp: clients[1] }), `?id=${chat.id}`)).json();
  assert.equal(complete.turns.length, 1); assert.equal(complete.turns[0].status, "complete"); assert.equal(modelState.calls, 1);
  assert.deepEqual(complete.turns[0].usage, { inputTokens: 120, outputTokens: 80 }); assert(complete.turns[0].modelStartedAt);
  assert.deepEqual(await service.command(auth, { action: "cancel", conversationId: chat.id, turnId: complete.turns[0].id }), { canceled: false }, "a completed answer is not represented as canceled");
  assert(complete.turns[0].evidence.some(item => item.links.some(link => link.href.startsWith("https://www.alamoplatform.com/"))));
  assert(!JSON.stringify(modelState.contexts).includes("OTHER_COMMUNITY_REPORT"));
  assert(!JSON.stringify(modelState.contexts).includes("PRIVATE_PATIENT"));
  assert(!JSON.stringify(modelState.contexts).includes("PRIVATE_RAW"));
  assert.equal((await request({ ...input, text: "Different request under same ID" })).status, 409);
  assert.equal((await request({ ...message(complete), expectedVersion: 0 })).status, 409);
  const restored = createConversationService({ store: fixture.newStore(), workStore: fixture.workStore, source: fixture.source, model: fixture.model, clientIds: clients.slice(0, 2) });
  assert.deepEqual(await restored.read(auth, chat.id), complete, "a new runtime reconstructs the complete transcript from disk");
  sourceFixture.state.document.grants[0].revoked = true;
  const denied = await request(null, fixture.token, `?id=${chat.id}`);
  assert.equal(denied.status, 403); assert(!JSON.stringify(await denied.json()).includes("published inspection"));
  const hiddenList = await (await request()).json();
  assert(hiddenList.conversations.every(item => item.locked && !item.title.includes("review")));
  sourceFixture.state.document.grants[0].revoked = false;
  await fixture.workStore.update(state => { state.assignments.find(item => item.skillId === "licensing").communityIds = ["345"]; });
  assert.equal((await request(null, fixture.token, `?id=${chat.id}`)).status, 403);
  await fixture.workStore.update(state => { state.assignments.find(item => item.skillId === "licensing").communityIds = ["337"]; });
  modelState.bad = true;
  const invalid = await (await request(message(complete))).json();
  assert.equal(invalid.turns.at(-1).status, "failed"); assert(!JSON.stringify(invalid).includes("invented-id"));
  modelState.bad = false;
  let release;
  let started;
  let waitStarted = new Promise(resolve => { started = resolve; });
  modelState.wait = () => { started(); return new Promise(resolve => { release = resolve; }); };
  let current = await service.read(auth, chat.id);
  const delayedInput = message(current);
  const delayed = request(delayedInput);
  await waitStarted;
  sourceFixture.state.document.grants[0].revoked = true;
  assert.equal((await request({ action: "cancel", conversationId: chat.id, turnId: delayedInput.requestId })).status, 200);
  release(); assert.equal((await delayed).status, 403);
  sourceFixture.state.document.grants[0].revoked = false;
  current = await service.read(auth, chat.id);
  assert.equal(current.turns.at(-1).status, "canceled"); assert.equal(current.turns.at(-1).answer, undefined);
  waitStarted = new Promise(resolve => { started = resolve; });
  const interrupted = request(message(current)); await waitStarted;
  modelState.time += 121_000;
  assert.equal((await service.read(auth, chat.id)).turns.at(-1).status, "interrupted");
  release(); await interrupted;
  assert.equal((await service.read(auth, chat.id)).turns.at(-1).answer, undefined, "late completion cannot publish after its lease expired");
  modelState.wait = async () => {};
  modelState.wait = async () => { sourceFixture.state.document.grants[0].revoked = true; };
  const revokedDuringAnswer = await request(message(await service.read(auth, chat.id)));
  assert.equal(revokedDuringAnswer.status, 403);
  sourceFixture.state.document.grants[0].revoked = false;
  assert.equal((await service.read(auth, chat.id)).turns.at(-1).status, "failed", "revocation prevents publication even without cancellation");
  modelState.wait = async () => {};
  const work = (await fixture.workStore.read()).value.work.find(item => item.skillId === "licensing" && item.status === "needs_review");
  const linked = await service.command(auth, { action: "create", requestId: randomUUID(), skillIds: ["licensing"], workId: work.id });
  const linkedAnswer = await service.command(auth, message(linked));
  assert.equal(linkedAnswer.turns[0].status, "complete");
  assert.match(modelState.contexts.at(-1).sourceSummaries[0].text, /Limited to the linked work/);
  assert.equal(modelState.contexts.at(-1).sourceSummaries.filter(item => !item.title.includes("availability")).length, 1);
  const baseline = (await fixture.workStore.read()).value.work.find(item => item.skillId === "licensing" && item.status === "completed" && !item.reviewedAt);
  const baselineChat = await service.command(auth, { action: "create", requestId: randomUUID(), skillIds: ["licensing"], workId: baseline.id });
  assert.deepEqual((await fixture.store.read()).value.conversations.find(item => item.id === baselineChat.id).resourceIds, [], "baseline monitoring receipts retain assignment scope instead of selecting an example report");
  const unavailable = createConversationService({ store: fixture.store, workStore: fixture.workStore, source: fixture.source,
    model: createConversationModel({ apiKey: "" }), clientIds: clients });
  await assert.rejects(unavailable.command(auth, message(await service.read(auth, chat.id))), /not configured/);
  assert.throws(() => validateConversationAnswer({ paragraphs: [{ kind: "evidence", text: "Invented", sourceIds: [] }] }, []));
  const persisted = await readFile(fixture.chatPath, "utf8");
  assert.doesNotMatch(persisted, /SYNTHETIC_MODEL_SECRET|PRIVATE_PATIENT|PRIVATE_RAW|Bearer |eyJhbGci/);
  await fixture.store.update(state => {
    const template = state.conversations[0];
    for (let group = 0; group < 2; group++) state.conversations.push({ ...structuredClone(template), id: randomUUID(), requestId: randomUUID(),
      turns: Array.from({ length: 25 }, () => ({ id: randomUUID(), text: "Synthetic completed turn", status: "complete", createdAt: new Date(modelState.time).toISOString() })) });
  });
  const beforeBudget = modelState.calls;
  assert.equal((await request(message(await service.read(auth, chat.id)))).status, 429);
  assert.equal(modelState.calls, beforeBudget, "daily submission limit prevents another provider call");
  console.log("Conversation checks passed: signed-token HTTP, host/user isolation, persisted cross-client continuation, idempotency, source scope/revocation, citation validation, cancellation, interrupted-turn recovery, no secret persistence and fail-closed model setup.");
} finally { await fixture.close(); }
