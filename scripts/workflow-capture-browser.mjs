import assert from 'node:assert/strict';
import { syntheticCapture, syntheticSopContent } from './workflow-capture-fixture.mjs';

export async function checkCapturePublication(page, artifacts) {
  const capture = syntheticCapture();
  const file = { name: 'synthetic-workflow-capture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(capture)) };
  const fill = (label, value) => page.getByLabel(label, { exact: true }).fill(value);
  const click = label => page.getByRole('button', { name: label, exact: true }).click();
  const saved = revision => page.getByText(`Saved · Revision ${revision}`, { exact: true }).waitFor();
  const endpoint = new URL(`/api/platform/workflow/v1/drafts/${capture.id}`, page.url()).href;
  const publicationEndpoint = endpoint.replace('/drafts/', '/published/');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await click('Create SOP');
  await fill('Title', 'Synthetic incomplete guided SOP');
  await click('Save draft'); await saved(1);
  assert(await page.getByRole('button', { name: 'Submit for review', exact: true }).isDisabled());
  await click('Import capture');
  await page.getByLabel('Workflow capture file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{') });
  await page.getByRole('alert').filter({ hasText: 'valid Workflow capture JSON' }).waitFor();
  await page.getByLabel('Workflow capture file').setInputFiles(file);
  await page.getByRole('checkbox', { name: /I reviewed these labels/ }).check();
  await page.route('**/api/platform/workflow/v1/drafts/*', route => route.request().method() === 'PUT' ? route.abort() : route.continue());
  await click('Create draft from capture');
  await page.getByRole('alert').filter({ hasText: 'Could not reach the server' }).waitFor();
  assert(await page.getByRole('checkbox', { name: /I reviewed these labels/ }).isChecked());
  await click('Create SOP'); await click('Keep editing');
  await page.unroute('**/api/platform/workflow/v1/drafts/*');
  await click('Create draft from capture'); await saved(1);
  const imported = (await (await page.request.get(endpoint)).json()).document;
  const complete = syntheticSopContent(capture, imported.content);
  await click('Use guided SOP');
  assert.equal(await page.getByLabel('Step 1 expected result', { exact: true }).inputValue(), '');
  await fill('Audience', complete.audience); await fill('Purpose', complete.purpose);
  for (const [label, key] of [['Accountable role', 'ownerRole'], ['When to start', 'trigger'], ['Where this applies', 'applicability'],
    ['Before starting', 'prerequisites'], ['Completion criteria', 'completionCriteria'], ['Exceptions and escalation', 'exceptions'], ['Handoff', 'handoff']]) await fill(label, complete.sop[key]);
  const quote = complete.sop.steps[0].action;
  await fill('Step 1 action', quote);
  await fill('Step 1 responsible role', complete.sop.steps[0].role);
  await fill('Step 1 expected result', complete.sop.steps[0].expectedResult);
  await click('Save draft'); await saved(2);
  const structured = (await (await page.request.get(endpoint)).json()).document;
  assert.deepEqual(structured.capture.bundle, capture);
  assert.deepEqual(structured.content.sop, complete.sop);
  await page.getByText('Preview guide', { exact: true }).click();
  assert.match(await page.locator('.sop-preview').innerText(), /fictional checklist/);
  await page.getByText('Preview guide', { exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: new URL('desktop-captured-sop.png', artifacts).pathname, fullPage: false });
  await click('+ Connect knowledge');
  await page.getByLabel('Connected entity', { exact: true }).selectOption('role:assessor');
  await fill('Exact evidence excerpt', quote);
  await fill('Why are these connected?', 'The authored action explicitly names this role; synthetic test only.');
  await click('Save proposed connection');
  await page.getByText('Proposed · Unapproved', { exact: true }).waitFor();
  await click('Submit for review'); await saved(3);
  assert(await page.getByLabel('Step 1 action', { exact: true }).isDisabled());
  await click('Review connection');
  await fill('Connection decision', 'Reviewed the captured SOP quotation and role source.');
  await click('Approve connection');
  await page.getByText('Connection approved', { exact: true }).waitFor();
  await fill('Review decision', 'Reviewed the synthetic SOP structure and retained source.');
  await click('Approve document'); await saved(4);
  await click('Load approved connections');
  await page.getByRole('checkbox', { name: 'Assessor', exact: true }).check();
  await click('Publish approved version'); await saved(5);
  await click('Read published version');
  await page.getByRole('article', { name: 'Published version', exact: true }).waitFor();
  const originalPublication = await (await page.request.get(publicationEndpoint)).json();
  assert.deepEqual(originalPublication.publication.document.content.sop, complete.sop);
  assert.deepEqual(originalPublication.publication.document.capture.bundle, capture);
  assert.equal(originalPublication.publication.rendering.rendererVersion, 1);
  assert.equal(originalPublication.citations[0].source.excerpt, quote);
  await page.reload();
  await page.locator('.drafts-list-item').filter({ hasText: capture.title }).click();
  await saved(5);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.workflow-sidebar')?.getBoundingClientRect().width === 72);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: new URL('mobile-captured-sop.png', artifacts).pathname, fullPage: false });
  await click('Read published version');
  const published = page.getByRole('article', { name: 'Published version', exact: true });
  await published.waitFor();
  assert.match(await published.innerText(), /Published content revision 2/);
  assert.match(await published.innerText(), /Target status: draft-reference/);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await click('Return to draft'); await saved(6);
  await fill('Step 1 expected result', 'A newly proposed outcome, not yet published.');
  await click('Save draft'); await saved(7);
  assert.deepEqual(await (await page.request.get(publicationEndpoint)).json(), originalPublication);
  await page.getByText('Evidence changed · Needs review', { exact: true }).waitFor();
  await click('Import capture');
  await page.getByLabel('Workflow capture file').setInputFiles(file);
  await page.getByRole('checkbox', { name: /I reviewed these labels/ }).check();
  await click('Create draft from capture'); await saved(7);
  assert.equal(await page.getByLabel('Step 1 expected result', { exact: true }).inputValue(), 'A newly proposed outcome, not yet published.');
  await click('← All drafts');
  await page.locator('.drafts-list-item').filter({ hasText: capture.title }).waitFor();
  await click('Knowledge'); await click('Drafts & review');
  await page.locator('.drafts-list-item').filter({ hasText: capture.title }).click();
  await saved(7);
  console.log('Captured SOP browser flow passed: import/retry, source-preserving structure, exact quote, separate reviews, publication, mobile/reload, draft successor and idempotent reimport.');
}
